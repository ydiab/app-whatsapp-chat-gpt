const fs = require("node:fs/promises");
const express = require("express");
const { randomUUID } = require("node:crypto");
const {
	getConversation,
	pushConversationMessage,
	setRecipeReady,
} = require("../store/conversationStore");
const { setLastCreatedRecipeId } = require("../store/lastRecipeByUser");
const { recipeStore } = require("../store/recipeStore");
const {
	uploadRecipeToCookidooAccount,
	uploadCookidooNativeToAccount,
} = require("../services/cookidooUpload");
const {
	validateRecipeForUpload,
	isStoredRecipeUsable,
	recipeToUploadPayload,
} = require("../utils/validateRecipe");

/**
 * REST API for the mobile app (app-mimi-mobile). Channel-agnostic twin of the
 * WhatsApp webhook: same stores and recipe AI, JSON in/out instead of Meta payloads.
 * `userId` is an opaque per-install id generated by the app.
 */
function createApiRouter({ config, recipeAi }) {
	const router = express.Router();

	async function hasCookidooCredentials() {
		try {
			await fs.access(config.cookidooCredentialsPath);
			const hasCookieEnv = Boolean(
				process.env.COOKIDOO_COOKIE_HEADER?.trim() ||
					process.env.COOKIDOO_COOKIES_JSON?.trim(),
			);
			if (!hasCookieEnv) {
				await fs.access(config.cookidooCookiesPath);
			}
			return true;
		} catch {
			return false;
		}
	}

	router.get("/health", (_req, res) => {
		res.json({ ok: true });
	});

	router.post("/chat", async (req, res) => {
		const userId = String(req.body?.userId || "").trim();
		const message = String(req.body?.message || "").trim();

		if (!userId || !message) {
			return res
				.status(400)
				.json({ error: "userId y message son obligatorios" });
		}

		try {
			pushConversationMessage(userId, "user", message);
			const conversation = getConversation(userId);

			const { content: reply, isComplete } =
				await recipeAi.generateThermomixProposal(conversation.messages, {
					channel: "app",
				});

			if (!reply) {
				throw new Error("La propuesta de receta llegó vacía");
			}

			pushConversationMessage(userId, "assistant", reply);

			if (!isComplete) {
				setRecipeReady(userId, false);
				return res.json({ reply, recipeReady: false });
			}

			try {
				const recipe = await recipeAi.generateRecipeForCookidoo(
					conversation.messages,
				);
				validateRecipeForUpload(recipe);
				const recipeId = randomUUID();
				recipeStore.set(recipeId, {
					id: recipeId,
					createdAt: new Date().toISOString(),
					...recipe,
				});
				setLastCreatedRecipeId(userId, recipeId);
				setRecipeReady(userId, true);
				return res.json({ reply, recipeReady: true, recipeId });
			} catch (prepError) {
				// La conversación sigue siendo válida: devolvemos la propuesta en texto
				// aunque no hayamos podido estructurarla para Cookidoo.
				console.error("Preparar receta Cookidoo (api):", prepError);
				setRecipeReady(userId, false);
				return res.json({ reply, recipeReady: false });
			}
		} catch (error) {
			console.error("Error en /api/chat:", error);
			return res.status(502).json({
				error:
					"Tuve un problema generando la respuesta. Inténtalo de nuevo con más detalle.",
			});
		}
	});

	router.get("/recipes/:id", (req, res) => {
		const stored = recipeStore.get(req.params.id);
		if (!stored) {
			return res.status(404).json({ error: "Receta no encontrada" });
		}
		// cookidooNative es el payload crudo de Cookidoo (grande e irrelevante para la UI)
		const { cookidooNative, ...recipe } = stored;
		return res.json(recipe);
	});

	router.post("/recipes/:id/upload", async (req, res) => {
		const stored = recipeStore.get(req.params.id);
		if (!stored) {
			return res.status(404).json({ error: "Receta no encontrada" });
		}

		if (!(await hasCookidooCredentials())) {
			return res.status(503).json({
				error:
					"Falta la sesión de Cookidoo en el servidor (COOKIDOO_COOKIE_HEADER).",
			});
		}

		try {
			let recipeUrl;
			let title;

			if (stored.cookidooNative?.content) {
				const result = await uploadCookidooNativeToAccount(
					stored.cookidooNative,
					config.cookidooCredentialsPath,
					config.cookidooCookiesPath,
				);
				recipeUrl = result.recipeUrl;
				title = stored.cookidooNative.content.name || stored.title || "Receta";
			} else {
				if (!isStoredRecipeUsable(stored)) {
					return res
						.status(409)
						.json({ error: "La receta guardada está incompleta" });
				}
				const recipe = recipeToUploadPayload(stored);
				validateRecipeForUpload(recipe);
				const result = await uploadRecipeToCookidooAccount(
					recipe,
					config.cookidooCredentialsPath,
					config.cookidooCookiesPath,
				);
				recipeUrl = result.recipeUrl;
				title = recipe.title;
			}

			return res.json({ title, recipeUrl });
		} catch (cookidooError) {
			console.error("Cookidoo upload error (api):", cookidooError);
			return res.status(502).json({
				error: `No pude subir la receta a Cookidoo: ${cookidooError.message}`,
			});
		}
	});

	return router;
}

module.exports = { createApiRouter };
